use std::{borrow::Cow, env, fs, path::PathBuf};

use anyhow::{Context as _, Result};
use specta::Types;
use specta_typescript::{Exporter, Typescript, semantic::Configuration};

fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for ch in name.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn main() -> Result<()> {
    let mut types = Types::default();
    let functions = koharu_app::protocol_functions(&mut types);
    let types = Configuration::empty()
        .enable_lossless_floats()
        .apply_types(&types);
    let functions_for_runtime = functions;

    let exporter = Exporter::from(
        Typescript::default().header("// generated by koharu; do not edit\n"),
    )
    .framework_runtime(move |exp| {
        let mut out = String::from("import { Channel, invoke } from \"./runtime\";\n\nexport { Channel };\n\nexport const commands = {\n");
        for function in &functions_for_runtime {
            let js_name = camel(function.name());
            let mut args = Vec::new();
            for (name, datatype) in function.args() {
                let js = camel(name);
                let inner = exp.inline(datatype)?;
                let ty = if name.starts_with("on_") {
                    format!("Channel<{inner}>")
                } else {
                    inner
                };
                args.push((js, ty));
            }
            let result = match function.result() {
                Some(datatype) => exp.inline(datatype)?,
                None => "void".into(),
            };
            let params = args
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect::<Vec<_>>()
                .join(", ");
            let names = args
                .iter()
                .map(|(name, _)| name.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            if args.is_empty() {
                out.push_str(&format!(
                    "  {js_name}: () => invoke<{result}>(\"{}\"),\n",
                    function.name()
                ));
            } else {
                out.push_str(&format!(
                    "  {js_name}: ({params}) => invoke<{result}>(\"{}\", {{ {names} }}),\n",
                    function.name()
                ));
            }
        }
        out.push_str("};\n");
        Ok(Cow::Owned(out))
    });

    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let path = manifest.join("../../packages/bridge/src/protocol.ts");
    exporter
        .export_to(&path, types.as_ref(), specta_serde::Format)
        .map_err(|error| anyhow::anyhow!("{error}"))?;
    let mut source = fs::read_to_string(&path).context("read generated protocol")?;
    if !source.ends_with('\n') {
        source.push('\n');
    }
    fs::write(&path, source).context("write generated protocol")?;
    Ok(())
}
