//! Writes `packages/ipc/src/protocol.ts`: every type the commands and events
//! carry, from specta's metadata, every command as a function over Tauri's
//! `invoke` that runs through the runner the interface sets, and every event
//! as a listener over its `listen`. tauri-specta has no release for Tauri 3 with
//! this specta, and the interface needs only this much of it.

use std::{borrow::Cow, fmt::Write as _, path::Path, sync::LazyLock};

use anyhow::{Context as _, Result};
use heck::ToLowerCamelCase as _;
use indoc::{formatdoc, indoc};
use specta::{
    Format, FormatError, Type, Types,
    datatype::{DataType, Function, NamedReferenceType, Primitive, Reference},
};
use specta_typescript::{Exporter, FrameworkExporter, Number, Typescript};
use specta_util::Remapper;

fn main() -> Result<()> {
    let mut types = Types::default();
    let functions = koharu_desktop::bindings(&mut types);
    let events = koharu_desktop::event_bindings(&mut types);
    let output = Path::new(env!("CARGO_WORKSPACE_DIR")).join("packages/ipc/src/protocol.ts");
    Exporter::from(Typescript::default())
        .framework_prelude(
            "// Generated by `cargo run -p koharu-desktop --bin ipc`, then `bun run format`. Do not edit this file manually.",
        )
        .framework_runtime(move |mut exporter| {
            let mut out = String::from(indoc! {r#"
                import { Channel, invoke, type InvokeOptions } from '@tauri-apps/api/core'
                import { listen, type UnlistenFn } from '@tauri-apps/api/event'

                export { Channel }

                /** Runs the command `command` by calling `invoke` with the options it sends, such as
                 * headers. */
                export type Runner = <T>(
                  command: string,
                  invoke: (options?: InvokeOptions) => Promise<T>,
                ) => Promise<T>

                let runner: Runner = (_, invoke) => invoke()

                /** Sets how every command runs, such as in a span whose trace it sends as headers. */
                export function setRunner(next: Runner): void {
                  runner = next
                }

            "#});
            out.push_str(&exporter.render_types()?);
            out.push_str(&commands(&exporter, &functions)?);
            out.push_str(&listeners(&exporter, &events)?);
            Ok(Cow::Owned(out))
        })
        .export_to(&output, &types, IpcFormat)
        .with_context(|| format!("failed to write {}", output.display()))?;
    println!("wrote {}", output.display());
    Ok(())
}

/// Every number as a TypeScript `number`: the ids, counts, and indices the
/// commands carry stay far below 2^53, and the IPC's JSON carries no NaN.
static NUMBERS: LazyLock<Remapper> = LazyLock::new(|| {
    let number = Number::<()>::definition(&mut Types::default());
    Remapper::new()
        .dangerous_bigints_as_number()
        .rule(Primitive::f32.into(), number.clone())
        .rule(Primitive::f64.into(), number)
});

/// The shapes the IPC's JSON carries: serde's, with every number a TypeScript
/// `number`.
struct IpcFormat;

impl Format for IpcFormat {
    fn map_types(&'_ self, types: &Types) -> Result<Cow<'_, Types>, FormatError> {
        let types = specta_serde::Format.map_types(types)?.into_owned();
        Ok(Cow::Owned(NUMBERS.remap_types(types)))
    }

    fn map_type(&'_ self, types: &Types, dt: &DataType) -> Result<Cow<'_, DataType>, FormatError> {
        let dt = specta_serde::Format.map_type(types, dt)?.into_owned();
        Ok(Cow::Owned(NUMBERS.remap_dt(dt)))
    }
}

/// `export const commands`: each command as a function of its arguments,
/// run through the runner, resolving to its `Ok` value; an `Err` rejects the
/// promise.
fn commands(
    exporter: &FrameworkExporter,
    functions: &[Function],
) -> Result<String, specta_typescript::Error> {
    let mut entries = String::new();
    for function in functions {
        let mut params = Vec::new();
        let mut keys = Vec::new();
        for (name, dt) in function.args() {
            let key = name.to_lower_camel_case();
            params.push(format!("{key}: {}", reference(exporter, dt)?));
            keys.push(key);
        }
        let result = match function.result() {
            Some(dt) => reference(exporter, dt)?,
            None => "null".to_owned(),
        };
        let docs = function
            .docs
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        if !docs.is_empty() {
            let _ = writeln!(entries, "/** {docs} */");
        }
        let _ = writeln!(
            entries,
            r#"{}: ({}) => runner("{name}", (options) => invoke<{result}>("{name}", {{ {} }}, options)),"#,
            function.name().to_lower_camel_case(),
            params.join(", "),
            keys.join(", "),
            name = function.name(),
        );
    }
    Ok(formatdoc! {"

        export const commands = {{
        {entries}}}
    "})
}

/// `export const events`: each event as a function of its handler, which
/// hears the event's payload, resolving to the function that stops it.
fn listeners(
    exporter: &FrameworkExporter,
    events: &[(&str, DataType)],
) -> Result<String, specta_typescript::Error> {
    let mut entries = String::new();
    for (name, dt) in events {
        let payload = exporter.reference(dt)?;
        let _ = writeln!(
            entries,
            r#"{}: (handler: (payload: {payload}) => void): Promise<UnlistenFn> => listen<{payload}>("{name}", (event) => handler(event.payload)),"#,
            name.to_lower_camel_case(),
        );
    }
    Ok(formatdoc! {"

        export const events = {{
        {entries}}}
    "})
}

/// A type as the interface takes it: a Tauri channel as `@tauri-apps/api`'s
/// `Channel`, and a `Result` as its `Ok` type, which a command resolves to.
fn reference(
    exporter: &FrameworkExporter,
    dt: &DataType,
) -> Result<String, specta_typescript::Error> {
    if let DataType::Reference(Reference::Named(reference)) = dt
        && let NamedReferenceType::Reference { generics, .. } = &reference.inner
        && let Some(named) = exporter.types.get(reference)
    {
        match (named.name.as_ref(), &generics[..]) {
            ("TAURI_CHANNEL", [(_, message)]) => {
                return Ok(format!("Channel<{}>", exporter.reference(message)?));
            }
            ("Result", [(_, ok), _]) => return exporter.reference(ok),
            _ => {}
        }
    }
    exporter.reference(dt)
}
