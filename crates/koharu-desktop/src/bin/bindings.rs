//! Writes `packages/bridge/src/protocol.ts`: every command as a function over
//! Tauri's `invoke`, every event as a listener over its `listen`, and every
//! type they carry, from specta's metadata. tauri-specta has no release for
//! Tauri 3 with this specta, and the bindings need only this much of it.

use std::{borrow::Cow, fmt::Write as _, path::Path};

use anyhow::{Context as _, Result};
use heck::ToLowerCamelCase as _;
use specta::{
    Format, FormatError, Type, Types,
    datatype::{DataType, Fields, Function, Generic, NamedReferenceType, Primitive, Reference},
};
use specta_typescript::{Exporter, FrameworkExporter, Number, Typescript};

fn main() -> Result<()> {
    let mut types = Types::default();
    let functions = koharu_desktop::bindings(&mut types);
    let events = koharu_desktop::event_bindings(&mut types);
    let output = Path::new(env!("CARGO_WORKSPACE_DIR")).join("packages/bridge/src/protocol.ts");
    Exporter::from(Typescript::default())
        .framework_prelude(
            "// Generated by `cargo run -p koharu-desktop --bin bindings`. Do not edit this file manually.",
        )
        .framework_runtime(move |mut exporter| {
            let mut out = String::from(
                "import { Channel, invoke } from \"@tauri-apps/api/core\";\nimport { listen, type UnlistenFn } from \"@tauri-apps/api/event\";\n\nexport { Channel };\n\n",
            );
            out.push_str(&exporter.render_types()?);
            out.push_str(&commands(&exporter, &functions)?);
            out.push_str(&listeners(&exporter, &events)?);
            Ok(Cow::Owned(out))
        })
        .export_to(&output, &types, Bridge)
        .with_context(|| format!("failed to write {}", output.display()))?;
    println!("wrote {}", output.display());
    Ok(())
}

/// serde's shapes, with every number a TypeScript `number`: the ids, counts,
/// and indices the commands carry stay far below 2^53, and the IPC's JSON
/// carries no NaN.
struct Bridge;

impl Format for Bridge {
    fn map_types(&'_ self, types: &Types) -> Result<Cow<'_, Types>, FormatError> {
        let types = specta_serde::Format.map_types(types)?.into_owned();
        Ok(Cow::Owned(types.map(|mut named| {
            if let Some(ty) = named.ty.as_mut() {
                numbers(ty);
            }
            named
        })))
    }

    fn map_type(&'_ self, types: &Types, dt: &DataType) -> Result<Cow<'_, DataType>, FormatError> {
        let mut dt = specta_serde::Format.map_type(types, dt)?.into_owned();
        numbers(&mut dt);
        Ok(Cow::Owned(dt))
    }
}

/// Makes every number in `dt` a TypeScript `number`. A map's keys stay as
/// they are, since JSON writes them as strings.
fn numbers(dt: &mut DataType) {
    match dt {
        DataType::Primitive(
            Primitive::usize
            | Primitive::isize
            | Primitive::u64
            | Primitive::i64
            | Primitive::u128
            | Primitive::i128
            | Primitive::f16
            | Primitive::f32
            | Primitive::f64
            | Primitive::f128,
        ) => *dt = Number::<()>::definition(&mut Types::default()),
        DataType::Primitive(_) | DataType::Generic(_) => {}
        DataType::List(list) => numbers(&mut list.ty),
        DataType::Map(map) => numbers(map.value_ty_mut()),
        DataType::Struct(r#struct) => fields(&mut r#struct.fields),
        DataType::Enum(r#enum) => {
            for (_, variant) in &mut r#enum.variants {
                fields(&mut variant.fields);
            }
        }
        DataType::Tuple(tuple) => tuple.elements.iter_mut().for_each(numbers),
        DataType::Nullable(inner) => numbers(inner),
        DataType::Intersection(all) => all.iter_mut().for_each(numbers),
        DataType::Reference(Reference::Named(named)) => match &mut named.inner {
            NamedReferenceType::Inline { dt, .. } => numbers(dt),
            NamedReferenceType::Reference { generics, .. } => {
                for (_, dt) in generics {
                    numbers(dt);
                }
            }
            NamedReferenceType::Recursive(_) => {}
        },
        DataType::Reference(Reference::Opaque(_)) => {}
    }
}

fn fields(fields: &mut Fields) {
    match fields {
        Fields::Unit => {}
        Fields::Unnamed(unnamed) => {
            for field in &mut unnamed.fields {
                field.ty.as_mut().map(numbers);
            }
        }
        Fields::Named(named) => {
            for (_, field) in &mut named.fields {
                field.ty.as_mut().map(numbers);
            }
        }
    }
}

/// `export const commands`: each command as a function of its arguments,
/// resolving to its `Ok` value; an `Err` rejects the promise.
fn commands(
    exporter: &FrameworkExporter,
    functions: &[Function],
) -> Result<String, specta_typescript::Error> {
    let mut out = String::from("\nexport const commands = {\n");
    for function in functions {
        let mut params = Vec::new();
        let mut keys = Vec::new();
        for (name, dt) in function.args() {
            let key = name.to_lower_camel_case();
            params.push(format!("{key}: {}", argument(exporter, dt)?));
            keys.push(key);
        }
        let result = match function.result() {
            Some(dt) => ok(exporter, dt)?,
            None => "null".to_owned(),
        };
        let docs = function.docs.trim();
        if !docs.is_empty() {
            let _ = writeln!(out, "\t/** {} */", docs.replace('\n', "\n\t * "));
        }
        let payload = if keys.is_empty() {
            String::new()
        } else {
            format!(", {{ {} }}", keys.join(", "))
        };
        let _ = writeln!(
            out,
            "\t{}: ({}) => invoke<{result}>(\"{}\"{payload}),",
            function.name().to_lower_camel_case(),
            params.join(", "),
            function.name(),
        );
    }
    out.push_str("};\n");
    Ok(out)
}

/// `export const events`: each event as a function of its handler, which
/// hears the event's payload, resolving to the function that stops it.
fn listeners(
    exporter: &FrameworkExporter,
    events: &[(&str, DataType)],
) -> Result<String, specta_typescript::Error> {
    let mut out = String::from("\nexport const events = {\n");
    for (name, dt) in events {
        let payload = exporter.reference(dt)?;
        let _ = writeln!(
            out,
            "\t{}: (handler: (payload: {payload}) => void): Promise<UnlistenFn> => listen<{payload}>(\"{name}\", (event) => handler(event.payload)),",
            name.to_lower_camel_case(),
        );
    }
    out.push_str("};\n");
    Ok(out)
}

/// An argument's type: a Tauri channel as `@tauri-apps/api`'s `Channel`.
fn argument(
    exporter: &FrameworkExporter,
    dt: &DataType,
) -> Result<String, specta_typescript::Error> {
    if let Some(("TAURI_CHANNEL", [(_, message)])) = named(exporter, dt) {
        return Ok(format!("Channel<{}>", exporter.reference(message)?));
    }
    exporter.reference(dt)
}

/// What a command resolves to: a `Result`'s `Ok` type.
fn ok(exporter: &FrameworkExporter, dt: &DataType) -> Result<String, specta_typescript::Error> {
    if let Some(("Result", [(_, ok), _])) = named(exporter, dt) {
        return exporter.reference(ok);
    }
    exporter.reference(dt)
}

/// A reference's named type's name and generic arguments.
fn named<'a>(
    exporter: &'a FrameworkExporter,
    dt: &'a DataType,
) -> Option<(&'a str, &'a [(Generic, DataType)])> {
    let DataType::Reference(Reference::Named(reference)) = dt else {
        return None;
    };
    let NamedReferenceType::Reference { generics, .. } = &reference.inner else {
        return None;
    };
    let name = exporter.types.get(reference)?.name.as_ref();
    Some((name, generics))
}
